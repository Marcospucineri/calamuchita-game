import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transformWithOxc } from 'vite';
const { code } = await transformWithOxc(readFileSync(new URL('../src/engine/AudioFocus.ts', import.meta.url),'utf8'), 'AudioFocus.ts');
const { bindAudioFocus } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
globalThis.document = Object.assign(new EventTarget(), { hidden: true });
globalThis.window = new EventTarget();
const audio = () => ({ state:'running', resumes:0, suspends:0, async resume(){ this.resumes++; this.state='running'; }, async suspend(){ this.suspends++; this.state='suspended'; } });
const music=audio(), engine=audio();
const cleanMusic=bindAudioFocus(music), cleanEngine=bindAudioFocus(engine);
assert.equal(music.state,'suspended');assert.equal(engine.state,'suspended');
window.dispatchEvent(new Event('pointerdown'));assert.equal(engine.resumes,0,'Hidden gestures must not unlock engine');
document.hidden=false;document.dispatchEvent(new Event('visibilitychange'));await Promise.resolve();
assert.equal(music.state,'running');assert.equal(engine.state,'running');
document.hidden=true;document.dispatchEvent(new Event('visibilitychange'));
assert.equal(music.state,'suspended');assert.equal(engine.state,'suspended');
document.hidden=false;window.dispatchEvent(new Event('pageshow'));await Promise.resolve();
assert.equal(engine.state,'running');window.dispatchEvent(new Event('pagehide'));
assert.equal(engine.state,'suspended');assert.equal(music.state,'suspended');
cleanMusic();cleanEngine();document.dispatchEvent(new Event('visibilitychange'));
assert.equal(engine.state,'suspended','Disposed bindings leave no active listeners');
console.log('OK: música y motor se pausan en segundo plano y vuelven al regresar.');
