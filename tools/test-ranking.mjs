import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
const db = new PGlite();
const uid = '00000000-0000-4000-8000-000000000001', other = '00000000-0000-4000-8000-000000000002';
const session = '10000000-0000-4000-8000-000000000001', session2 = '10000000-0000-4000-8000-000000000002';
try {
  await db.exec(`create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;`);
  await db.exec(fs.readFileSync('supabase/migrations/202610160001_progress.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/202610160002_distance_ranking.sql','utf8'));
  await db.exec(`insert into auth.users values ('${uid}'),('${other}'); insert into public.player_progress(user_id,save) values ('${uid}','{"progress":{"profile":{"name":"Luz"}}}'),('${other}','{"progress":{"profile":{"name":"Axel"}}}'); set request.jwt.claim.sub='${uid}';`);
  const record = (s, seconds, car, plane=0, foot=0) => db.query('select public.record_distance($1::uuid,$2,$3,$4,$5)',[s,seconds,car,plane,foot]);
  const ranking = async (c) => (await db.query('select * from public.distance_ranking($1)',[c])).rows;
  await record(session,0,0);
  await db.exec(`update public.distance_sessions set created_at=now()-interval '10 minutes'`);
  await record(session,100,1000,2000,100);
  await record(session,100,1000,2000,100);
  await record(session,50,500,1000,50);
  assert.equal((await ranking('car'))[0].meters,1000,'Retries and old packets cannot double count');
  await record(session2,20,500);
  assert.equal((await ranking('car'))[0].meters,1500,'Concurrent devices/sessions add distances');
  assert.equal((await ranking('plane'))[0].meters,2000);
  assert.equal((await ranking('foot'))[0].meters,100);
  await assert.rejects(record(session,100,1e8),'Impossible speed rejected');
  await assert.rejects(record(session,-1,0),'Negative values rejected');
  await assert.rejects(record(session,100,NaN),'NaN rejected');
  await assert.rejects(record(session,1e6,0),'Future play time rejected');
  await assert.rejects(ranking('inventada'));
  await db.exec(`set request.jwt.claim.sub='${other}';`);
  await record(session,25,2000);
  let rows=await ranking('car');
  assert.deepEqual(rows.map(r=>r.name),['Axel','Luz']);
  assert.deepEqual(rows.map(r=>r.is_me),[true,false]);
  assert.equal(rows[0].position,1);
  await record(session,25,2000,100,0);
  rows=await ranking('foot');assert.equal(rows.at(-1).is_me,true);assert.equal(rows.at(-1).position,null,'Own zero distance is shown without ranking');
  await db.exec(`set role authenticated;`);
  await assert.rejects(db.query('select * from public.distance_sessions'),'Session details private');
  await assert.rejects(db.query('update public.player_distances set car=99999'),'Direct writes forbidden');
  assert.ok((await ranking('car')).length>0,'Authenticated users can read only sanitized ranking');
  await db.exec(`reset role; set request.jwt.claim.sub=''; set role anon;`);
  await assert.rejects(ranking('car'),'Anonymous ranking denied');
  await assert.rejects(record(session,0,0),'Anonymous participation denied');
  await db.exec(`reset role; set request.jwt.claim.sub='${uid}';
    insert into auth.users select ('20000000-0000-4000-8000-' || lpad(i::text,12,'0'))::uuid from generate_series(1,60) i;
    insert into public.player_distances(user_id,car) select id,10000 from auth.users where id::text like '20000000%';`);
  const outsideTop=await ranking('car');
  assert.equal(outsideTop.length,51,'Top 50 plus own row when outside top 50');
  assert.ok(outsideTop.find((r)=>r.is_me).position>50);
  console.log('OK: ranking por categoría, sesiones idempotentes, varios dispositivos, límites y acceso solo autenticado.');
} finally { await db.close(); }
const server = await createServer({ configFile:false, server:{middlewareMode:true}, appType:'custom', logLevel:'error' });
try {
  const { traveledMeters } = await server.ssrLoadModule('/src/services/Distances.ts');
  const from={x:0,y:0,z:0};
  assert.equal(traveledMeters('car',.1,from,{x:2,y:10,z:0}),2,'Car counts horizontal movement');
  assert.equal(traveledMeters('plane',.1,from,{x:3,y:4,z:0}),5,'Flight counts actual 3D path');
  assert.equal(traveledMeters('foot',.1,from,{x:.3,y:1,z:.4}),.5,'Jumping in place does not add walking kilometers');
  assert.equal(traveledMeters('car',.1,from,{x:100,y:0,z:0}),0,'Teleport rejected');
  assert.equal(traveledMeters('plane',1,from,{x:10,y:0,z:0}),0,'Long gaps do not count');
  console.log('OK: distancia real por medio de transporte; saltos y teletransportes excluidos.');
} finally { await server.close(); }
