import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transformWithOxc } from 'vite';
const source = readFileSync(new URL('../src/gameplay/Progress.ts', import.meta.url), 'utf8');
const { code: js } = await transformWithOxc(source, 'Progress.ts');
const { newProgress, normalizeProfile, postalRewards, tripReward } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const pois = JSON.parse(readFileSync(new URL('../public/world/pois.json', import.meta.url)));
const town = pois.find((p) => p.town).town;
const townIds = pois.filter((p) => p.town === town).map((p) => p.id);
assert.equal(postalRewards(pois, []), 0);
assert.equal(postalRewards(pois, [pois[0].id, pois[0].id, 'inventada']), 50);
assert.equal(postalRewards(pois, townIds), townIds.length * 50 + 200);
assert.equal(postalRewards(pois, pois.map((p) => p.id)), pois.length * 50 + new Set(pois.map((p) => p.town).filter(Boolean)).size * 200);
assert.deepEqual([0, 999, 1000, 2000, 4000, 99999].map(tripReward), [20, 20, 30, 40, 60, 60]);
const a = newProgress(), b = newProgress(); a.profile.appearance.shirt = '#ffffff';
assert.notEqual(a.profile.appearance.shirt, b.profile.appearance.shirt);
assert.equal(normalizeProfile({ name: '  ', appearance: {} }).name, 'Visitante');
assert.equal(normalizeProfile({ name: 'x'.repeat(100), appearance: {} }).name.length, 24);
assert.equal(normalizeProfile({ name: 'Luz', appearance: { skin: 'bad' } }).appearance.skin, b.profile.appearance.skin);
console.log('OK: recompensas de postales, pueblos, tramos y perfil.');
