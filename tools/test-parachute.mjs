import assert from 'node:assert/strict';
import * as THREE from 'three';
import RAPIER from '@dimforge/rapier3d-compat';
import { createServer } from 'vite';
await RAPIER.init();
const context=new Proxy({}, {get:()=>()=>{}});
globalThis.document={createElement:()=>({width:0,height:0,getContext:()=>context})};
const server=await createServer({configFile:false,server:{middlewareMode:true},appType:'custom',logLevel:'error'});
try {
  const {Character}=await server.ssrLoadModule('/src/player/Character.ts');
  const {PlayerController}=await server.ssrLoadModule('/src/player/PlayerController.ts');
  const {Aircraft}=await server.ssrLoadModule('/src/player/Aircraft.ts');
  const world=new RAPIER.World({x:0,y:-9.81,z:0});
  world.createCollider(RAPIER.ColliderDesc.cuboid(2000,.5,2000).setTranslation(0,-.5,0));world.step();
  const data={heightAt:()=>0,heightAtXZ:()=>0,meta:{playArea:{x0:-2000,x1:2000,n0:-2000,n1:2000}}};
  const physics={world,castDown:(x,z,y,range)=>{const hit=world.castRay(new RAPIER.Ray({x,y,z},{x:0,y:-1,z:0}),range,true,RAPIER.QueryFilterFlags.ONLY_FIXED);return hit?y-hit.timeOfImpact:null;}};
  const scene=new THREE.Scene();
  const person=new Character(physics,scene);
  const car={occupied:false,speed:0,rotation:new THREE.Quaternion(),position:new THREE.Vector3(100,1,100),doorPoint:()=>new THREE.Vector3(100,0,98),forward:()=>new THREE.Vector3(1,0,0),place(){},reset(){},fixedUpdate(){},postStep(){}};
  const plane=new Aircraft(data,scene,physics,{x:0,n:0,heading:0});
  const player=new PlayerController(car,person,physics,data,plane);
  const input={interactPressed:false,resetPressed:false,moveX:0,moveY:0,jump:false,run:false,planeThrottle:0,planeBrake:0,steer:0,pitch:0};
  const step=()=>{player.fixedUpdate(1/60,input,0);world.step();player.postStep();person.render(1,1/60);};
  const action=()=>player.handleActions({...input,interactPressed:true});
  player.selectVehicle('plane');assert.equal(player.action.label,'Bajarse de la avioneta');
  action();assert.equal(player.mode,'onfoot');assert.equal(person.airState,null);assert.equal(plane.active,false);
  assert.equal(player.vehicle,'plane','Plane context survives exiting');
  assert.equal(player.action.label,'Subir a la avioneta');action();assert.equal(player.mode,'flying');assert.equal(plane.active,true);
  plane.currPos.set(0,300,0);plane.prevPos.copy(plane.currPos);plane.grounded=false;plane.speed=45;plane.altitude=300;
  assert.equal(player.action.label,'Saltar de la avioneta');action();assert.equal(player.mode,'onfoot');assert.equal(person.airState,'freefall');assert.equal(plane.occupied,false);
  const initialX=plane.position.x;
  for(let i=0;i<120;i++)step();
  assert.ok(person.verticalSpeed<-35,'Freefall accelerates downward');assert.ok(plane.position.x>initialX,'Abandoned plane keeps moving');
  assert.equal(player.action.label,'Abrir paracaídas');action();assert.equal(person.airState,'parachute');
  assert.equal(player.action,null,'Cannot reopen or board in midair');
  for(let i=0;i<90;i++)step();
  assert.ok(Math.abs(person.verticalSpeed+4.5)<.01,'Canopy slows the descent');assert.equal(person.parachute.visible,true);
  const x=person.position.x;input.moveX=1;for(let i=0;i<60;i++)step();assert.ok(person.position.x>x,'Canopy can be steered');input.moveX=0;
  for(let i=0;i<6000&&person.airborne;i++)step();
  assert.equal(person.airState,null,'Ground contact returns to walking');assert.equal(person.parachute.visible,false);assert.ok(person.position.y<.2);
  person.spawn(new THREE.Vector3(20,100,0),0);person.startFalling({x:0,y:-20,z:0});person.openParachute();player.selectVehicle('car');assert.equal(person.parachute.visible,false,'Changing vehicle cleans up canopy');
  const {encodeState,decodeState}=await server.ssrLoadModule('/src/multiplayer/protocol.ts');
  for(const mode of ['d','h'])assert.equal(decodeState(encodeState({x:0,y:300,z:0,qx:0,qy:0,qz:0,qw:1,speed:40,mode})).mode,mode);
  world.free();
  console.log('OK: bajar y subir a la avioneta, salto, caída acelerada, apertura, dirección, aterrizaje y estados multiplayer.');
} finally {await server.close();}
